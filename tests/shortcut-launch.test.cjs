const {test} = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const {launchHarness} = require('./helpers/launch-harness.cjs')
const id = '8a1cf954-9641-4848-8a07-3568cf90fad4'
const argv = ['Drive Tambu.exe', '--', '--open-folder', id]

// Regression targets: unconditional showWindow() in second-instance/handleShortcut,
// unconditional ready-to-show, missing '--' in generated launchers, and reordered argv.
for (const platform of ['win32', 'linux']) {
  test(`${platform}: a cold shortcut opens the saved folder without ever showing the panel`, async t => {
    const h = await launchHarness(t, {platform, argv})
    assert.deepEqual(h.calls.opened, [h.localPath])
    assert.equal(h.windows.length, 1)
    assert.equal(h.calls.shown, 0)
    assert.equal(h.calls.focused, 0)
    assert.equal(h.windows[0].visible, false)
    assert.equal(h.calls.quits, 0)
  })
  test(`${platform}: a warm shortcut does not reveal a hidden panel`, async t => {
    const h = await launchHarness(t, {platform})
    h.windows[0].hide(); h.resetWindowCounts()
    await h.secondary(argv)
    assert.deepEqual(h.calls.opened, [h.localPath])
    assert.equal(h.calls.shown, 0)
    assert.equal(h.calls.focused, 0)
    assert.equal(h.windows[0].visible, false)
  })
}
test('a delayed ready-to-show cannot flash the panel after a successful shortcut', async t => {
  const h = await launchHarness(t, {argv, deferReady: true})
  h.windows[0].emit('ready-to-show')
  await h.settle()
  assert.deepEqual(h.calls.opened, [h.localPath])
  assert.equal(h.calls.shown, 0)
})
test('a disconnected folder connects silently even with autoConnect disabled', async t => {
  let release
  const connecting = new Promise(resolve => {release = resolve})
  const h = await launchHarness(t, {argv, status: 'disconnected', connect: () => connecting})
  assert.deepEqual(h.calls.connected, [id])
  const before = {shown: h.calls.shown, opened: [...h.calls.opened]}
  release(); await h.settle()
  assert.equal(before.shown, 0)
  assert.deepEqual(before.opened, [])
  assert.deepEqual(h.calls.opened, [h.localPath])
  assert.equal(h.calls.shown, 0)
})
test('a shortcut does not refocus or explicitly hide a panel that is already visible', async t => {
  const h = await launchHarness(t)
  assert.equal(h.windows[0].visible, true)
  h.resetWindowCounts()
  await h.secondary(argv)
  assert.deepEqual(h.calls.opened, [h.localPath])
  assert.equal(h.windows[0].visible, true)
  assert.equal(h.calls.shown, 0)
  assert.equal(h.calls.focused, 0)
})
test('ordinary startup still shows the app and a normal second launch restores it', async t => {
  const h = await launchHarness(t)
  assert.equal(h.windows[0].visible, true)
  h.windows[0].hide()
  await h.secondary(['Drive Tambu.exe'])
  assert.equal(h.windows[0].visible, true)
  assert.deepEqual(h.calls.opened, [])
})
test('no tray available keeps the app reachable rather than invisibly running', async t => {
  const h = await launchHarness(t, {argv, noTray: true})
  assert.equal(h.windows[0].visible, true)
  assert.deepEqual(h.calls.opened, [h.localPath])
})
test('a process that loses the single-instance lock never creates a window', async t => {
  const h = await launchHarness(t, {argv, secondaryProcess: true})
  assert.equal(h.windows.length, 0)
  assert.equal(h.calls.quits, 1)
  assert.deepEqual(h.calls.opened, [])
})
test('the original startup arguments are forwarded as structured additionalData', async t => {
  const h = await launchHarness(t, {argv, secondaryProcess: true})
  assert.deepEqual(h.calls.lockData, {driveTambuArgv: argv})
})
test('a warm launch uses original additionalData, not reordered Electron argv', async t => {
  const h = await launchHarness(t)
  h.windows[0].hide(); h.resetWindowCounts()
  await h.secondary(['Drive Tambu.exe', '--open-folder', '--original-process-start-time=123', id], {driveTambuArgv: argv})
  assert.deepEqual(h.calls.errors, [])
  assert.deepEqual(h.calls.opened, [h.localPath])
  assert.equal(h.calls.shown, 0)
})
test('invalid forwarded data reveals a useful error and cannot fall back to a different folder', async t => {
  const h = await launchHarness(t)
  h.windows[0].hide()
  await h.secondary(argv, {driveTambuArgv: 'not an argument array'})
  assert.deepEqual(h.calls.opened, [])
  assert.equal(h.calls.errors.length, 1)
  assert.equal(h.windows[0].visible, true)
})
test('an unknown folder shows an error, never fabricates a configuration or a mount', async t => {
  const h = await launchHarness(t, {argv: ['app', '--', '--open-folder', 'unknown-123']})
  assert.equal(h.windows[0].visible, true)
  assert.equal(h.calls.errors.length, 1)
  assert.deepEqual(h.calls.connected, [])
  assert.deepEqual(h.calls.opened, [])
  assert.equal(h.snapshot().mounts.length, 1)
})
test('connection failure from a cold shortcut displays the app and the actual error', async t => {
  const h = await launchHarness(t, {argv, status: 'disconnected', connect: async () => {throw new Error('Server non raggiungibile')}})
  assert.equal(h.windows[0].visible, true)
  assert.match(h.calls.errors[0].message, /Server non raggiungibile/)
  assert.deepEqual(h.calls.opened, [])
})
test('an Explorer opening error is not silently swallowed', async t => {
  const h = await launchHarness(t, {argv, openError: 'Apertura non riuscita'})
  assert.equal(h.windows[0].visible, true)
  assert.equal(h.calls.errors[0].message, 'Apertura non riuscita')
})
test('a pending safety operation still refuses the shortcut and remains visible', async t => {
  const h = await launchHarness(t, {preflightKind: 'blocked'})
  const request = h.invoke('drive:disconnect', id)
  await h.settle()
  assert.equal(h.snapshot().operation.phase, 'blocked')
  await h.secondary(argv)
  assert.deepEqual(h.calls.opened, [])
  assert.deepEqual(h.calls.connected, [])
  assert.equal(h.windows[0].visible, true)
  await h.invoke('drive:respondToOperation', h.snapshot().operation.id, 'cancel')
  await request
})
test('request-exit from an installer still asks through the guarded quit flow', async t => {
  const h = await launchHarness(t)
  await h.secondary(['app', '--request-exit'])
  assert.equal(h.snapshot().operation.kind, 'quit')
  assert.equal(h.snapshot().operation.phase, 'confirm')
  assert.equal(h.calls.quits, 0)
  assert.deepEqual(h.calls.opened, [])
  await h.invoke('drive:respondToOperation', h.snapshot().operation.id, 'cancel')
})
test('a newly generated Windows shortcut includes -- and opens without a panel flash', async t => {
  const h = await launchHarness(t)
  const file = await h.invoke('drive:createShortcut', id)
  const shortcut = JSON.parse(fs.readFileSync(file, 'utf8'))
  assert.equal(shortcut.args, `-- --open-folder ${id}`)
  h.windows[0].hide(); h.resetWindowCounts()
  await h.secondary([shortcut.target, ...shortcut.args.split(' ')])
  assert.deepEqual(h.calls.opened, [h.localPath])
  assert.equal(h.calls.shown, 0)
})

test('closing an expanded window with X leaves it hidden and the next ordinary opening is compact', async t => {
  const h = await launchHarness(t)
  await h.invoke('drive:setWindowMode', 'expanded')
  assert.equal(h.snapshot().windowMode, 'expanded')
  let prevented = false
  h.windows[0].emit('close', {preventDefault() {prevented = true}})
  assert.equal(prevented, true)
  assert.equal(h.windows[0].isVisible(), false)
  // The window stays expanded while hidden; the reset happens on the next normal show.
  assert.equal(h.snapshot().windowMode, 'expanded')
  await h.secondary(['Drive Tambu.exe'])
  assert.equal(h.snapshot().windowMode, 'compact')
  assert.equal(h.windows[0].isVisible(), true)
  assert.deepEqual(h.calls.opened, [])
})

test('temporary hiding never changes expanded mode on normal reopening', async t => {
  const h = await launchHarness(t)
  await h.invoke('drive:setWindowMode', 'expanded')
  await h.invoke('drive:hideWindow')
  await h.secondary(['Drive Tambu.exe'])
  assert.equal(h.snapshot().windowMode, 'expanded')
})

test('explicit Apri finestra from tray overrides the pending compact reopening', async t => {
  const h = await launchHarness(t)
  await h.invoke('drive:setWindowMode', 'expanded')
  h.windows[0].emit('close', {preventDefault() {}})
  const expand = h.trays[0].menu.find(item => item.label === 'Apri finestra')
  assert.ok(expand)
  expand.click()
  assert.equal(h.snapshot().windowMode, 'expanded')
  await h.secondary(['Drive Tambu.exe'])
  assert.equal(h.snapshot().windowMode, 'expanded')
})

test('closing during a blocked operation does not change the expanded mode', async t => {
  const h = await launchHarness(t, {preflightKind: 'blocked'})
  await h.invoke('drive:setWindowMode', 'expanded')
  const request = h.invoke('drive:disconnect', h.id)
  await h.settle()
  assert.equal(h.snapshot().operation.phase, 'blocked')
  h.windows[0].emit('close', {preventDefault() {}})
  await h.secondary(['Drive Tambu.exe'])
  assert.equal(h.snapshot().windowMode, 'expanded')
  await h.invoke('drive:respondToOperation', h.snapshot().operation.id, 'cancel')
  await request
})

test('new Windows shortcuts target the bundled fast launcher, record an inventory entry and retain the saved ID', async t => {
  const h=await launchHarness(t, {nativeLauncher:true})
  const file=await h.invoke('drive:createShortcut',id)
  const link=JSON.parse(fs.readFileSync(file,'utf8'))
  assert.match(link.target,/DriveTambuShortcut\.exe$/)
  assert.equal(link.args,`--open-folder ${id}`)
  const inventory=JSON.parse(fs.readFileSync(h.root+'/shortcuts-v1.json','utf8'))
  assert.equal(inventory.shortcuts[0].id,id)
  assert.equal(inventory.shortcuts[0].path,file)
})

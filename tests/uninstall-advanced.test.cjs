const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'..')
const nsis=()=>fs.readFileSync(path.join(root,'build/installer.nsh'),'utf8')
const ps=()=>fs.readFileSync(path.join(root,'build/uninstall-cleanup.ps1'),'utf8')
test('advanced uninstall provides three unchecked choices and separate manual component control',()=>{
 const s=nsis();for(const label of ['Elimina impostazioni','Elimina collegamenti creati','Elimina backup verificati','Gestisci componenti di sistema']) assert.ok(s.includes(label),label)
 assert.ok((s.match(/\$\{NSD_Uncheck\}/g)||[]).length>=3)
 assert.match(s,/\$\{Silent\}/);assert.match(s,/\$\{isUpdated\}/);assert.match(s,/\$installMode == "CurrentUser"/)
 assert.match(s,/ms-settings:appsfeatures/)
})
test('cleanup is an installer-embedded standalone script, and never invokes Electron or bulk-deletes directories',()=>{
 const s=nsis(),f=ps()
 assert.match(s,/File \/oname=.*uninstall-cleanup\.ps1/)
 assert.match(s,/ExecWait.*powershell/)
 assert.doesNotMatch(f,/rclone (?:delete|purge)|taskkill|Remove-Item\s+[^\r\n]*-Recurse|\.exe --open-folder/i)
 assert.match(f,/ConvertFrom-Json/)
 assert.match(f,/\.drive-tambu-backup\.json/)
 assert.match(f,/ReparsePoint/)
 assert.match(f,/FileIndex|fileId|FileId/i)
 assert.match(f,/ELIMINA/)
})
test('legacy shortcuts are identified by both target path and strict single folder ID, never by displayed filename',()=>{
 const code=ps()
 assert.match(code,/WScript\.Shell/)
 assert.match(code,/\.TargetPath/)
 assert.match(code,/\.Arguments/)
 assert.match(code,/Drive Tambu\.exe/)
 assert.match(code,/DriveTambuShortcut\.exe/)
 assert.match(code,/shortcuts-v1\.json/)
 assert.match(code,/Desktop/)
 assert.match(code,/\\bopen-folder\\b|open-folder/)
})
test('Windows CI runs cleanup self-tests and includes actual native-launcher compilation before installer',()=>{
 const flow=fs.readFileSync(path.join(root,'.github/workflows/build.yml'),'utf8')
 assert.match(flow,/uninstall-cleanup\.ps1.*-SelfTest/)
 const pkg=require('../package.json')
 assert.match(pkg.scripts['dist:win'],/build:native:win/)
})

test('new registered shortcuts can be removed even after their folder was removed from settings, but only with exact inventory identity',()=>{
 const code=ps()
 assert.match(code,/inventoried/);assert.match(code,/expected\.id/);assert.match(code,/expected\.args/);assert.match(code,/expected\.target/)
 assert.match(code,/unknown-inventory-id/)
})
